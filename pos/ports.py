"""External contracts expressed in domain values, rather than platform payloads."""
from typing import Protocol
from .domain import Customer, Prescription, Staff, Store, Variant


class UpstreamError(Exception):
    def __init__(self, message, uncertain=False, retryable=False, status=None):
        self.message, self.uncertain, self.retryable, self.status = message, uncertain, retryable, status
        super().__init__(message)


class Commerce(Protocol):
    def customer(self, phone: str) -> Customer: ...
    def stores(self) -> list[Store]: ...
    def variants(self) -> list[Variant]: ...
    def available(self, item_id: int, location_id: int) -> int: ...
    def orders(self, location_id: int | None = None) -> list[dict]: ...
    def order(self, order_id: int) -> dict: ...
    def validate_order(self, snapshot: dict, invoice_no: str, operation_key: str) -> None: ...
    def validate_refund(self, order_id: int, refund: dict) -> None: ...
    def create_order(self, snapshot: dict, invoice_no: str, operation_key: str, charge: dict) -> dict: ...
    def create_refund(self, order_id: int, refund: dict, credit_note: str, operation_key: str, reason: str) -> dict: ...


class StoreTool(Protocol):
    def prescriptions(self, phone: str) -> list[Prescription]: ...
    def staff(self, store_code: str) -> list[Staff]: ...


class Terminal(Protocol):
    def find_charge(self, operation_key: str) -> dict | None: ...
    def charge(self, amount_paise: int, method: str, operation_key: str, expires_at: str | None = None) -> dict: ...
    def status(self, charge_id: str) -> dict: ...
    def refund(self, charge_id: str, amount_paise: int, reason: str) -> dict: ...
